"""Dataset for Stage-2 (Risk Selection & Reasoning).

This dataset consumes:
  1) a label jsonl (your existing train/val jsonl that contains `targets` with `bbox_xyxy`)
  2) a proposals jsonl generated by Stage-1 (YOLO/Detector), containing `proposals`.

Output per sample:
  - pixel_values: [T, 3, S, S]  (letterboxed or direct resize, same as Phase1)
  - proposals: [N, 4] normalized xyxy in [0,1] w.r.t. the resized image size S
  - proposal_conf: [N]
  - proposal_cls: [N]
  - gt_box: [4] normalized xyxy in [0,1]
  - gt_mask: [N] bool label for each proposal (IoU>=thr with gt_box)

Design choices
--------------
* We use the **same video loading / sampling / letterbox** code path as Phase1,
  so your training scripts remain consistent.
* Stage-2 does NOT learn to predict boxes; it learns to score/select boxes.
"""

from __future__ import annotations

import json
import os
from dataclasses import dataclass
from typing import Any, Dict, List, Optional, Tuple

import numpy as np
import torch
from PIL import Image
from torch.utils.data import Dataset

from drama_fast.utils.path_resolver import resolve_clip_dir, resolve_local_image_path


def _iter_jsonl(path: str):
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            yield json.loads(line)


def box_iou_xyxy(a: torch.Tensor, b: torch.Tensor, eps: float = 1e-6) -> torch.Tensor:
    """Pairwise IoU for xyxy boxes.

    a: [N,4], b: [M,4]
    returns: [N,M]
    """
    if a.numel() == 0 or b.numel() == 0:
        return a.new_zeros((a.shape[0], b.shape[0]))
    a = a.float()
    b = b.float()
    tl = torch.maximum(a[:, None, :2], b[None, :, :2])
    br = torch.minimum(a[:, None, 2:], b[None, :, 2:])
    wh = (br - tl).clamp(min=0)
    inter = wh[..., 0] * wh[..., 1]
    area_a = (a[:, 2] - a[:, 0]).clamp(min=0) * (a[:, 3] - a[:, 1]).clamp(min=0)
    area_b = (b[:, 2] - b[:, 0]).clamp(min=0) * (b[:, 3] - b[:, 1]).clamp(min=0)
    union = area_a[:, None] + area_b[None, :] - inter
    return inter / (union + eps)


@dataclass
class Stage2Sample:
    sample_id: str
    image_url: str
    targets: List[Dict[str, Any]]


class DramaStage2Dataset(Dataset):
    def __init__(
        self,
        label_jsonl: str,
        proposals_jsonl: str,
        data_root: str,
        img_size: int = 384,
        num_frames: int = 8,
        frame_stride: int = 2,
        use_letterbox: bool = True,
        letterbox_fill: int = 114,
        flip_prob: float = 0.0,
        topk_proposals: int = 80,
        iou_pos_thr: float = 0.5,
        return_meta: bool = False,
        split: str = "train",
        **_ignored,
    ):
        self.label_jsonl = label_jsonl
        self.proposals_jsonl = proposals_jsonl
        self.data_root = data_root
        self.img_size = int(img_size)
        self.num_frames = int(num_frames)
        self.frame_stride = int(frame_stride)
        self.use_letterbox = bool(use_letterbox)
        self.letterbox_fill = int(letterbox_fill)
        self.flip_prob = float(flip_prob)
        self.topk_proposals = int(topk_proposals)
        self.iou_pos_thr = float(iou_pos_thr)
        self.return_meta = bool(return_meta)
        self.split = str(split)

        self.items: List[Stage2Sample] = []
        for obj in _iter_jsonl(label_jsonl):
            sid = obj.get("sample_id") or obj.get("id") or obj.get("uid")
            img = obj.get("image")
            if not sid or not img:
                raise ValueError(f"Bad label jsonl line: keys={list(obj.keys())}")
            targets = obj.get("targets", [])
            if not isinstance(targets, list):
                targets = []
            self.items.append(Stage2Sample(sample_id=str(sid), image_url=str(img), targets=targets))

        # proposals index by sample_id
        self.proposals_by_id: Dict[str, Dict[str, Any]] = {}
        for pobj in _iter_jsonl(proposals_jsonl):
            sid = pobj.get("sample_id")
            if not sid:
                continue
            self.proposals_by_id[str(sid)] = pobj

        missing = sum(1 for it in self.items if it.sample_id not in self.proposals_by_id)
        if missing > 0:
            raise RuntimeError(
                f"[DramaStage2Dataset] proposals missing for {missing}/{len(self.items)} samples. "
                f"Check that Stage-1 ran on the same split and sample_id matches."
            )

    def __len__(self):
        return len(self.items)

    def _letterbox_params(self, W: int, H: int):
        S = int(self.img_size)
        scale = float(S) / float(max(W, H))
        new_w = int(round(W * scale))
        new_h = int(round(H * scale))
        new_w = min(new_w, S)
        new_h = min(new_h, S)
        pad_x = (S - new_w) // 2
        pad_y = (S - new_h) // 2
        sx = new_w / float(W) if W > 0 else 1.0
        sy = new_h / float(H) if H > 0 else 1.0
        return sx, sy, new_w, new_h, pad_x, pad_y

    def _letterbox_to_tensor(self, img: Image.Image, new_w: int, new_h: int, pad_x: int, pad_y: int) -> torch.Tensor:
        S = int(self.img_size)
        img_resized = img.resize((new_w, new_h), resample=Image.BILINEAR)
        canvas = Image.new("RGB", (S, S), color=(self.letterbox_fill,) * 3)
        canvas.paste(img_resized, (pad_x, pad_y))
        arr = np.array(canvas)
        t = torch.from_numpy(arr).permute(2, 0, 1).float() / 255.0
        return t

    def _normalize_box_letterbox(self, box_xyxy, W: int, H: int, sx: float, sy: float, pad_x: int, pad_y: int):
        x1, y1, x2, y2 = [float(v) for v in box_xyxy]
        x1 = max(0.0, min(x1, float(W)))
        x2 = max(0.0, min(x2, float(W)))
        y1 = max(0.0, min(y1, float(H)))
        y2 = max(0.0, min(y2, float(H)))
        if x2 < x1:
            x1, x2 = x2, x1
        if y2 < y1:
            y1, y2 = y2, y1

        x1 = x1 * sx + pad_x
        x2 = x2 * sx + pad_x
        y1 = y1 * sy + pad_y
        y2 = y2 * sy + pad_y
        S = float(self.img_size)
        return torch.tensor([x1 / S, y1 / S, x2 / S, y2 / S], dtype=torch.float32).clamp(0, 1)

    def _normalize_box_direct(self, box_xyxy, W: int, H: int):
        x1, y1, x2, y2 = [float(v) for v in box_xyxy]
        x1 = max(0.0, min(x1, float(W)))
        x2 = max(0.0, min(x2, float(W)))
        y1 = max(0.0, min(y1, float(H)))
        y2 = max(0.0, min(y2, float(H)))
        if x2 < x1:
            x1, x2 = x2, x1
        if y2 < y1:
            y1, y2 = y2, y1
        return torch.tensor([x1 / float(W), y1 / float(H), x2 / float(W), y2 / float(H)], dtype=torch.float32).clamp(0, 1)

    def _load_clip(self, clip_dir: str, keyframe_path: str) -> Tuple[torch.Tensor, Tuple[int, int], Dict[str, Any]]:
        """Load T frames into [T,3,S,S]."""
        # Re-use Phase1 logic: list frames, find keyframe index, sample around it.
        # Here we keep it simple: use sorted frames in clip_dir and take a centered window.
        frame_paths = sorted(
            [os.path.join(clip_dir, p) for p in os.listdir(clip_dir) if p.lower().endswith((".jpg", ".png", ".jpeg"))]
        )
        if len(frame_paths) == 0:
            raise FileNotFoundError(f"No frames found in clip_dir={clip_dir}")

        # keyframe index (fallback to middle if not found)
        try:
            kidx = frame_paths.index(keyframe_path)
        except ValueError:
            # match by basename
            kb = os.path.basename(keyframe_path)
            idxs = [i for i, p in enumerate(frame_paths) if os.path.basename(p) == kb]
            kidx = idxs[0] if idxs else len(frame_paths) // 2

        T = int(self.num_frames)
        stride = int(self.frame_stride)
        half = (T // 2) * stride
        start = max(0, kidx - half)
        idxs = [min(len(frame_paths) - 1, start + i * stride) for i in range(T)]
        sel_paths = [frame_paths[i] for i in idxs]

        # load first frame for size and letterbox params
        img0 = Image.open(sel_paths[0]).convert("RGB")
        W, H = img0.size
        sx, sy, new_w, new_h, pad_x, pad_y = self._letterbox_params(W, H)

        frames = []
        for p in sel_paths:
            im = Image.open(p).convert("RGB")
            if self.use_letterbox:
                t = self._letterbox_to_tensor(im, new_w=new_w, new_h=new_h, pad_x=pad_x, pad_y=pad_y)
            else:
                im2 = im.resize((self.img_size, self.img_size), resample=Image.BILINEAR)
                arr = np.array(im2)
                t = torch.from_numpy(arr).permute(2, 0, 1).float() / 255.0
            frames.append(t)
        video = torch.stack(frames, dim=0)  # [T,3,S,S]

        letterbox_meta = {
            "sx": float(sx),
            "sy": float(sy),
            "pad_x": int(pad_x),
            "pad_y": int(pad_y),
            "new_w": int(new_w),
            "new_h": int(new_h),
            "img_size": int(self.img_size),
            "use_letterbox": bool(self.use_letterbox),
        }
        return video, (W, H), {"frame_paths": sel_paths, "letterbox": letterbox_meta}

    def __getitem__(self, idx: int) -> Dict[str, Any]:
        it = self.items[idx]
        # Your label jsonl uses `image` as the keyframe reference.
        # We map it to a local file path using the existing resolver.
        keyframe_path = resolve_local_image_path(it.image_url, data_root=self.data_root)
        clip_dir = resolve_clip_dir(it.image_url, data_root=self.data_root)

        video, (W, H), clip_meta = self._load_clip(clip_dir=clip_dir, keyframe_path=keyframe_path)
        sx, sy, pad_x, pad_y = (
            clip_meta["letterbox"]["sx"],
            clip_meta["letterbox"]["sy"],
            clip_meta["letterbox"]["pad_x"],
            clip_meta["letterbox"]["pad_y"],
        )

        # GT: use first target as "primary" (consistent with your fast_sup jsonl)
        if it.targets:
            gt_xyxy = it.targets[0]["bbox_xyxy"]
            if self.use_letterbox:
                gt_box = self._normalize_box_letterbox(gt_xyxy, W=W, H=H, sx=sx, sy=sy, pad_x=pad_x, pad_y=pad_y)
            else:
                gt_box = self._normalize_box_direct(gt_xyxy, W=W, H=H)
        else:
            gt_box = torch.zeros(4, dtype=torch.float32)

        # proposals
        pobj = self.proposals_by_id[it.sample_id]
        props = pobj.get("proposals", [])
        props = props[: self.topk_proposals]

        p_boxes = []
        p_conf = []
        p_cls = []
        for p in props:
            bxyxy = p.get("bbox_xyxy")
            if bxyxy is None:
                continue
            if self.use_letterbox:
                nb = self._normalize_box_letterbox(bxyxy, W=W, H=H, sx=sx, sy=sy, pad_x=pad_x, pad_y=pad_y)
            else:
                nb = self._normalize_box_direct(bxyxy, W=W, H=H)
            p_boxes.append(nb)
            p_conf.append(float(p.get("conf", 0.0)))
            p_cls.append(int(p.get("cls", -1)))

        if len(p_boxes) == 0:
            # ensure at least one dummy proposal to keep shapes stable
            p_boxes = [torch.zeros(4, dtype=torch.float32)]
            p_conf = [0.0]
            p_cls = [-1]

        proposals = torch.stack(p_boxes, dim=0)  # [N,4]
        proposal_conf = torch.tensor(p_conf, dtype=torch.float32)
        proposal_cls = torch.tensor(p_cls, dtype=torch.int64)

        # assign positive labels by IoU
        ious = box_iou_xyxy(proposals, gt_box[None, :]).squeeze(1)  # [N]
        gt_mask = ious >= float(self.iou_pos_thr)

        # optional flip augmentation
        do_flip = (self.flip_prob > 0) and (np.random.rand() < self.flip_prob)
        if do_flip:
            # video [T,3,S,S] -> flip width
            video = torch.flip(video, dims=[3])
            # boxes: x -> 1-x
            x1 = proposals[:, 0].clone()
            x2 = proposals[:, 2].clone()
            proposals[:, 0] = 1.0 - x2
            proposals[:, 2] = 1.0 - x1
            x1g, x2g = gt_box[0].item(), gt_box[2].item()
            gt_box[0] = 1.0 - x2g
            gt_box[2] = 1.0 - x1g

            # enforce order
            x1n = torch.minimum(proposals[:, 0], proposals[:, 2])
            x2n = torch.maximum(proposals[:, 0], proposals[:, 2])
            proposals[:, 0], proposals[:, 2] = x1n, x2n
            proposals.clamp_(0.0, 1.0)
            gt_box = gt_box.clamp(0.0, 1.0)

        out: Dict[str, Any] = {
            "pixel_values": video,  # [T,3,S,S]
            "proposals": proposals,  # [N,4]
            "proposal_conf": proposal_conf,
            "proposal_cls": proposal_cls,
            "gt_box": gt_box,  # [4]
            "gt_mask": gt_mask,  # [N]
        }

        if self.return_meta:
            out["meta"] = {
                "sample_id": it.sample_id,
                "image_url": it.image_url,
                "clip_dir": clip_dir,
                "keyframe_path": keyframe_path,
                "orig_size": (W, H),
                **clip_meta,
            }

        return out


def stage2_collate(batch: List[Dict[str, Any]]) -> Dict[str, Any]:
    """Pad proposals to max N in batch."""
    B = len(batch)
    T, C, S, _ = batch[0]["pixel_values"].shape

    pixel_values = torch.stack([b["pixel_values"] for b in batch], dim=0)  # [B,T,3,S,S]
    # match Phase1 input shape [B,3,T,S,S]
    pixel_values = pixel_values.permute(0, 2, 1, 3, 4).contiguous()

    gt_box = torch.stack([b["gt_box"] for b in batch], dim=0)

    maxN = max(int(b["proposals"].shape[0]) for b in batch)
    props = torch.zeros((B, maxN, 4), dtype=torch.float32)
    conf = torch.zeros((B, maxN), dtype=torch.float32)
    cls = torch.full((B, maxN), -1, dtype=torch.int64)
    mask = torch.zeros((B, maxN), dtype=torch.bool)
    gt_mask = torch.zeros((B, maxN), dtype=torch.bool)

    for i, b in enumerate(batch):
        n = int(b["proposals"].shape[0])
        props[i, :n] = b["proposals"]
        conf[i, :n] = b["proposal_conf"]
        cls[i, :n] = b["proposal_cls"]
        mask[i, :n] = True
        gt_mask[i, :n] = b["gt_mask"]

    out = {
        "pixel_values": pixel_values,  # [B,3,T,S,S]
        "proposals": props,
        "proposal_conf": conf,
        "proposal_cls": cls,
        "proposal_mask": mask,
        "gt_box": gt_box,
        "gt_mask": gt_mask,
    }

    if "meta" in batch[0]:
        meta_list = [b.get("meta") for b in batch]
        out["meta"] = meta_list
        # convenience: expose sample_id directly for debugging / evaluation
        try:
            out["sample_id"] = [m.get("sample_id") for m in meta_list]
        except Exception:
            pass
    return out


